using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Halsa.Backend.Infrastructure.Database.Auditoria;

/// <summary>
/// Un acceso de emergencia (break-the-glass, SPEC 08) pendiente de revisión, en <c>auditoria.revisiones_emergencia</c>.
/// Lo crea <c>AuditWriter</c> en la misma operación que la fila de <c>auditoria.accesos</c> a la que apunta
/// <see cref="AccesoId"/>. Varios accesos del mismo actor al mismo caso en 1 h comparten una revisión.
/// </summary>
internal sealed class RevisionEmergencia
{
    /// <summary>Lo que tiene el oficial de privacidad para revisar.</summary>
    public static readonly TimeSpan PlazoRevision = TimeSpan.FromHours(72);

    /// <summary>La ventana en que los accesos del mismo actor al mismo caso se agrupan.</summary>
    public static readonly TimeSpan VentanaAgrupacion = TimeSpan.FromHours(1);

    public Guid Id { get; init; }

    /// <summary>El tenant del caso, no el del actor.</summary>
    public string TenantId { get; init; } = string.Empty;

    /// <summary>La primera fila de <c>auditoria.accesos</c> de la revisión (FK lógica: la tabla está particionada).</summary>
    public Guid AccesoId { get; init; }

    public string ActorId { get; init; } = string.Empty;

    public Guid CasoMedicoId { get; init; }

    public string Motivo { get; init; } = string.Empty;

    public DateTimeOffset OcurridoEn { get; init; }

    public DateTimeOffset VenceRevisionEn { get; init; }

    public DateTimeOffset? RevisadoEn { get; set; }

    public string? RevisadoPor { get; set; }

    /// <summary><c>JUSTIFICADO</c> o <c>INJUSTIFICADO</c>.</summary>
    public string? Conclusion { get; set; }

    public string? Observaciones { get; set; }
}

internal sealed class RevisionEmergenciaConfiguration : IEntityTypeConfiguration<RevisionEmergencia>
{
    public const string Tabla = "revisiones_emergencia";

    public void Configure(EntityTypeBuilder<RevisionEmergencia> builder)
    {
        builder.ToTable(Tabla, Schemas.Auditoria);

        builder.HasKey(r => r.Id).HasName("pk_revisiones_emergencia");

        // Nothing generated by the database: no RETURNING, so the insert never evaluates the SELECT policy.
        builder.Property(r => r.Id).ValueGeneratedNever();
        builder.Property(r => r.TenantId).HasMaxLength(20);
        builder.Property(r => r.ActorId).HasMaxLength(64);
        builder.Property(r => r.Motivo).HasMaxLength(500);
        builder.Property(r => r.RevisadoPor).HasMaxLength(64);

        // A close updates WHERE revisado_en IS NULL: two officers closing at once, the second matches no row and
        // EF reports a concurrency conflict (409), instead of the immutability trigger raising (500).
        builder.Property(r => r.RevisadoEn).IsConcurrencyToken();
        builder.Property(r => r.Conclusion).HasMaxLength(15);
        builder.Property(r => r.Observaciones).HasMaxLength(2000);

        builder.HasIndex(r => new { r.TenantId, r.RevisadoEn, r.VenceRevisionEn })
            .HasDatabaseName("ix_revisiones_emergencia_tenant_pendientes");

        builder.HasIndex(r => new { r.ActorId, r.CasoMedicoId, r.OcurridoEn })
            .HasDatabaseName("ix_revisiones_emergencia_actor_caso");
    }
}
